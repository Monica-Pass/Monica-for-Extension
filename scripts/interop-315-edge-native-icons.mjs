import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { expect } from '@playwright/test';
import { loginEditor, save, readItem } from './interop-315-edge-features.mjs';

export async function runNativeIconUi({page,evidence,screenshot,output}) {
  const input = resolve('.tmp/keepass-android-interop/run-n745HP/android-aes.kdbx');
  const password = 'monica-android-extension-interop-password';
  await page.getByRole('button',{name:'密码源',exact:true}).click();
  await page.locator('m3e-list-action').filter({hasText:'连接 KeePass'}).click();
  const dialog = page.getByRole('dialog',{name:'连接 KeePass',exact:true});
  await dialog.getByLabel('显示名称',{exact:true}).fill('Native icon test');
  await dialog.getByLabel('KeePass 数据库文件',{exact:true}).setInputFiles(input);
  await dialog.getByLabel('数据库密码（可留空）',{exact:true}).fill(password);
  await dialog.getByRole('button',{name:'解锁并连接',exact:true}).click();
  await dialog.waitFor({state:'hidden',timeout:60000});
  const card = page.locator('[data-home-provider-id]').filter({has:page.getByRole('heading',{name:'Native icon test',exact:true})});
  const providerId = await card.getAttribute('data-home-provider-id');assert.ok(providerId);
  const flush = async () => {
    await page.setViewportSize({width:1280,height:900});
    await page.getByRole('button',{name:'密码源',exact:true}).click();
    await card.getByRole('button',{name:/^(立即同步|重试同步|写入本机副本)$/}).first().click();
    await expect(card.getByRole('button',{name:'取消同步',exact:true})).toHaveCount(0,{timeout:60000});
    await expect(card.locator('.form-error')).toHaveCount(0);
    await page.getByRole('button',{name:/^全部项目/}).click();
  };
  await flush();
  const listed = await page.evaluate(()=>chrome.runtime.sendMessage({type:'VAULT_LIST_ITEMS'}));assert.equal(listed.ok,true);
  const id=listed.data.find(item=>item.title==='GitHub' && item.providerRefs.some(ref=>ref.providerId===providerId))?.id;assert.ok(id);
  const original = await readItem(page,id);
  const open = async () => {
    await page.getByLabel('搜索密码库',{exact:true}).fill('GitHub');
    await page.getByLabel('查看GitHub详情',{exact:true}).first().click();
    return page.locator('[role="dialog"][data-item-kind="login"]');
  };
  const imageLoaded = async locator => expect.poll(()=>locator.evaluate(img=>img.naturalWidth)).toBeGreaterThan(0);
  const capture = async name => {
    const item = await readItem(page,id);
    const result = await page.evaluate(providerId=>chrome.runtime.sendMessage({type:'KEEPASS_EXPORT_FILE',providerId}),providerId);assert.equal(result.ok,true);
    await writeFile(join(output,`${name}.kdbx`),Buffer.from(result.data.file,'base64'));
    return {name,value:item.customIconValue,type:item.customIconType};
  };
  let detail = await open();await imageLoaded(detail.locator('.website-icon img'));
  await detail.getByRole('button',{name:'编辑',exact:true}).click();
  let editor=loginEditor(page);
  await page.setViewportSize({width:420,height:920});
  await editor.getByRole('button',{name:'更换图标',exact:true}).click();
  await editor.getByLabel('搜索图标名称',{exact:true}).fill('github');
  await editor.getByRole('button',{name:'github',exact:true}).click();
  await imageLoaded(editor.locator('.icon-current img'));
  await screenshot(page,'native-icon-brand-420.png');
  await save(editor);await flush();
  const stages=[await capture('native-icon-brand')];assert.equal(stages[0].type,'KEEPASS_CUSTOM_ICON');assert.ok(stages[0].value);
  detail=await open();await imageLoaded(detail.locator('.website-icon img'));await detail.getByRole('button',{name:'编辑',exact:true}).click();editor=loginEditor(page);
  await page.setViewportSize({width:320,height:860});
  await editor.getByRole('button',{name:'更换图标',exact:true}).click();
  await editor.getByRole('button',{name:'Emoji',exact:true}).click();
  await editor.getByLabel('Emoji',{exact:true}).fill('👩🏽‍💻');await editor.getByRole('button',{name:'使用这个 Emoji',exact:true}).click();
  const emojiTarget=await editor.locator('.emoji-grid button').first().boundingBox();assert.ok(emojiTarget && emojiTarget.width>=48 && emojiTarget.height>=48);
  assert.equal(await editor.evaluate(node=>node.scrollWidth>node.clientWidth),false);
  await editor.locator('.icon-current').scrollIntoViewIfNeeded();
  await screenshot(page,'native-icon-emoji-320.png');
  await save(editor);await flush();stages.push(await capture('native-icon-emoji'));
  detail=await open();await imageLoaded(detail.locator('.website-icon img'));await detail.getByRole('button',{name:'编辑',exact:true}).click();editor=loginEditor(page);
  await page.setViewportSize({width:420,height:920});await editor.getByRole('button',{name:'更换图标',exact:true}).click();
  await editor.getByLabel('从图片选择',{exact:true}).setInputFiles({name:'bad.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg></svg>')});
  await expect(editor.getByRole('alert')).toContainText('请选择 PNG、JPEG 或 WebP 图片');
  await editor.getByLabel('从图片选择',{exact:true}).setInputFiles({name:'upload.png',mimeType:'image/png',buffer:Buffer.from(stages[0].value,'base64')});
  await expect(editor.getByRole('status')).toHaveCount(0);await imageLoaded(editor.locator('.icon-current img'));
  await screenshot(page,'native-icon-upload-420.png');await save(editor);await flush();stages.push(await capture('native-icon-upload'));
  detail=await open();await detail.getByRole('button',{name:'编辑',exact:true}).click();editor=loginEditor(page);await editor.getByRole('button',{name:'更换图标',exact:true}).click();await editor.getByRole('button',{name:'跟随网站',exact:true}).click();await editor.getByRole('button',{name:'取消',exact:true}).click();
  assert.equal((await readItem(page,id)).customIconValue,stages[2].value);
  detail=await open();await detail.getByRole('button',{name:'编辑',exact:true}).click();editor=loginEditor(page);await editor.getByRole('button',{name:'更换图标',exact:true}).click();await editor.getByRole('button',{name:'跟随网站',exact:true}).click();await save(editor);await flush();stages.push(await capture('native-icon-clear'));
  assert.equal((await readItem(page,id)).password,original.password);
  assert.equal(stages[3].value,undefined);
  await writeFile(join(output,'native-icon-stages.json'),JSON.stringify({password,stages},null,2));
  evidence.nativeIconUi={status:'passed',importPreview:true,brand:true,emoji:true,imageUpload:true,invalidImageRejected:true,cancelPreserved:true,clear:true,passwordUnchanged:true,widths:[320,420,1280]};
}
