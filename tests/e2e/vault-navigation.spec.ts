import { chooseOption, dialogContent } from "./fixtures/material";
import { expect, test } from "@playwright/test";
import { launchEdgeContext } from "./fixtures/edge";
import path from "node:path";
import { homeBackup, homePassword } from "./fixtures/vault-home";

test("top filter combines database, favorites, type and folders without duplicate list controls", async ({}, info) => {
  test.setTimeout(120_000);
  const extension = path.resolve("dist");
  const context = await launchEdgeContext(info.outputPath("profile"), { locale: "zh-CN", viewport: { width: 1200, height: 950 }, args: [`--disable-extensions-except=${extension}`, `--load-extension=${extension}`] });
  try {
    const worker = context.serviceWorkers()[0] || await context.waitForEvent("serviceworker");
    const page = await context.newPage(); await page.goto(`chrome-extension://${new URL(worker.url()).host}/index.html`);
    const backup = await homeBackup();
    expect(await page.evaluate(async ({ backup, password }) => chrome.runtime.sendMessage({ type: "VAULT_RESTORE_ENCRYPTED", backup, backupPassword: password }), { backup, password: homePassword })).toMatchObject({ ok: true });
    await page.reload();
    await expect(page.getByText("Everyday Visa", { exact: true })).toBeVisible();
    await expect(page.locator('.vault-browse-bar').getByRole('combobox')).toHaveCount(0);
    await expect(page.locator('.vault-browse-bar').getByRole('button', { name: '收藏', exact: true })).toHaveCount(0);
    const open = page.getByRole("button", { name: "筛选", exact: true });
    const filters = dialogContent(page, { name: "筛选密码库" });
    await open.click();
    const database = filters.getByRole("combobox", { name: "当前数据库", exact: true });
    const favorite = filters.getByRole("button", { name: "收藏", exact: true });
    await chooseOption(database, "work-db");
    await filters.getByRole('button', { name: /Accounts/ }).click();
    await filters.getByRole('button', { name: '完成', exact: true }).click();
    await expect(page.getByText("GitHub · Monica Studio", { exact: true })).toBeVisible();
    await expect(page.getByText("Proton Mail", { exact: true })).toHaveCount(0);
    await open.click();
    await chooseOption(database, "local");
    await expect(filters.getByRole('button', { name: '全部文件夹', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await favorite.focus(); await page.keyboard.press('Space');
    await expect(favorite).toHaveAttribute('aria-pressed', 'true');
    await chooseOption(filters.getByRole("combobox", { name: "项目类型", exact: true }), "card");
    await expect(filters.locator('.filter-result-count')).toHaveText('1 个结果');
    await page.screenshot({ path: info.outputPath('filters-desktop.png'), animations: 'disabled' });
    await filters.getByRole("button", { name: "完成", exact: true }).click();
    await expect(open).toBeFocused();
    await expect(page.locator(".item-card")).toHaveCount(1);
    await expect(page.getByText("Everyday Visa", { exact: true })).toBeVisible();
    await expect(open.locator('.filter-count')).toHaveText('3');
    await open.click();
    await chooseOption(database, 'empty-db');
    await expect(filters.locator('.filter-result-count')).toHaveText('0 个结果');
    await filters.getByRole("button", { name: "清除筛选", exact: true }).click();
    await expect(database).toHaveJSProperty('value', 'all');
    await expect(favorite).toHaveAttribute('aria-pressed', 'false');
    await expect(filters.getByRole('combobox', {name: '项目类型', exact: true})).toHaveJSProperty('value', 'all');
    await expect(filters.getByRole('button', { name: '清除筛选', exact: true })).toBeDisabled();
    await filters.getByRole('button', { name: '完成', exact: true }).focus();
    await page.keyboard.press('Tab');
    await expect(filters.getByRole('button', { name: '关闭筛选', exact: true })).toBeFocused();
    await page.keyboard.press('Shift+Tab');
    await expect(filters.getByRole('button', { name: '完成', exact: true })).toBeFocused();
    for (const width of [360, 320]) {
      await page.setViewportSize({width, height: 850});
      await page.emulateMedia({colorScheme: 'dark'});
      await page.evaluate(size => { document.documentElement.style.fontSize = size; }, width === 320 ? '200%' : '125%');
      await expect.poll(() => filters.evaluate(n => n.scrollWidth <= n.clientWidth + 1)).toBe(true);
      const footer = await filters.locator('footer').boundingBox();
      expect(footer!.x).toBeGreaterThanOrEqual(0); expect(footer!.y + footer!.height).toBeLessThanOrEqual(850);
      await page.screenshot({path: info.outputPath(`filters-${width}-dark.png`), animations: 'disabled'});
    }
    await page.keyboard.press('Escape');
    await expect(filters).toHaveCount(0);
    await expect(open).toBeFocused();
    await page.setViewportSize({width:1200, height:950});
    await page.evaluate(() => { document.documentElement.style.fontSize = ''; });
    await page.locator('#primary-navigation').getByRole('button', {name: /^登录项/}).click();
    await expect(page.locator('.page-heading')).toHaveCount(0);
    await expect(page.getByText('登录密码只在解锁后显示和编辑。', {exact:true})).toHaveCount(0);
    await expect(page.getByText('Proton Mail', {exact:true})).toBeVisible();
    await page.screenshot({path: info.outputPath('logins-clean.png'), animations: 'disabled'});
    await open.click(); await chooseOption(database, 'work-db');
    await filters.getByRole('button', {name: '完成', exact: true}).click();
    await page.reload();
    await page.locator('#primary-navigation').getByRole('button', {name: /^登录项/}).click();
    await expect(page.getByText('GitHub · Monica Studio', {exact:true})).toBeVisible();
    await expect(page.getByText('Proton Mail', {exact:true})).toHaveCount(0);
    await expect(page.getByText('Previous workspace', {exact:true})).toHaveCount(0);
    await expect(page.getByText('Retired account', {exact:true})).toHaveCount(0);
  } finally { await context.close(); }
});
